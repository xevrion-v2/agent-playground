/**
 * Gets the symbol for a currency code.
 */
export function getCurrencySymbol(currencyCode: string): string {
  return CURRENCY_SYMBOLS[currencyCode.toUpperCase()] ?? currencyCode;
}

/**
 * Gets the number of decimal places for a currency.
 */
export function getCurrencyDecimals(currencyCode: string): number {
  return CURRENCY_DECIMALS[currencyCode.toUpperCase()] ?? 2;
}

/**
 * Checks if a currency code is valid/supported.
 */
export function isValidCurrency(currencyCode: string): boolean {
  return (ALL_CURRENCIES as readonly string[]).includes(currencyCode.toUpperCase());
}

/**
 * Checks if a currency is a fiat currency.
 */
export function isFiatCurrency(currencyCode: string): boolean {
  return (FIAT_CURRENCIES as readonly string[]).includes(currencyCode.toUpperCase());
}

/**
 * Checks if a currency is a cryptocurrency.
 */
export function isCryptoCurrency(currencyCode: string): boolean {
  return (CRYPTO_CURRENCIES as readonly string[]).includes(currencyCode.toUpperCase());
}

